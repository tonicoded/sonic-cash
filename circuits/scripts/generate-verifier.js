const snarkjs = require("snarkjs");
const fs = require("fs");
const path = require("path");

async function main() {
    console.log("📄 Generating Solidity verifier for Sonic Privacy Pool...");
    
    const buildDir = path.join(__dirname, "../build");
    const circuitName = "withdrawal";
    const zkeyFile = path.join(buildDir, `${circuitName}_final.zkey`);
    const verifierFile = path.join(__dirname, "../../contracts/contracts/Verifier.sol");
    
    if (!fs.existsSync(zkeyFile)) {
        console.log("❌ Proving key not found. Please run setup first:");
        console.log("   npm run circuits:setup");
        return;
    }
    
    try {
        // Generate Solidity verifier
        console.log("🔄 Exporting Solidity verifier...");
        const solidityVerifier = await snarkjs.zKey.exportSolidityVerifier(zkeyFile);
        
        // Add custom header and modifications for our use case
        const customVerifier = `// SPDX-License-Identifier: MIT
// Auto-generated by snarkjs for Sonic Privacy Pool
pragma solidity ^0.8.19;

${solidityVerifier}

/*
 * This verifier contract was automatically generated from the withdrawal circuit.
 * 
 * Circuit proves:
 * - Knowledge of secret corresponding to a commitment in Merkle tree
 * - Generation of unique nullifier to prevent double-spending  
 * - Validation of recipient address and relayer fee
 * 
 * Public inputs (in order):
 * [0] root - Merkle tree root
 * [1] nullifier - Unique nullifier hash
 * [2] recipient - Recipient address (as field element)
 * [3] fee - Relayer fee amount
 */`;
        
        // Write verifier to contracts directory
        fs.writeFileSync(verifierFile, customVerifier);
        console.log(`✅ Solidity verifier exported to: ${verifierFile}`);
        
        // Generate verification key for frontend
        const vKey = await snarkjs.zKey.exportVerificationKey(zkeyFile);
        const frontendVkeyFile = path.join(__dirname, "../../frontend/public/verification_key.json");
        fs.writeFileSync(frontendVkeyFile, JSON.stringify(vKey, null, 2));
        console.log(`✅ Verification key exported for frontend: ${frontendVkeyFile}`);
        
        // Copy WASM and zkey files to frontend public directory
        const wasmFile = path.join(buildDir, `${circuitName}_js/${circuitName}.wasm`);
        const frontendWasmFile = path.join(__dirname, "../../frontend/public/withdrawal.wasm");
        const frontendZkeyFile = path.join(__dirname, "../../frontend/public/withdrawal.zkey");
        
        if (fs.existsSync(wasmFile)) {
            fs.copyFileSync(wasmFile, frontendWasmFile);
            console.log(`✅ WASM copied to frontend: ${frontendWasmFile}`);
        }
        
        if (fs.existsSync(zkeyFile)) {
            fs.copyFileSync(zkeyFile, frontendZkeyFile);
            console.log(`✅ Proving key copied to frontend: ${frontendZkeyFile}`);
        }
        
        // Generate TypeScript types for the frontend
        const typesContent = `// Auto-generated types for Sonic Privacy Pool ZK proofs
export interface WithdrawalInputs {
  // Private inputs
  secret: string;
  nullifier_secret: string;
  path_elements: string[];
  path_indices: string[];
  
  // Public inputs
  root: string;
  nullifier: string;
  recipient: string;
  fee: string;
}

export interface PLONKProof {
  a: [string, string];
  b: [[string, string], [string, string]];
  c: [string, string];
  z: [string, string];
  t1: [string, string];
  t2: [string, string];
  t3: [string, string];
  Wxi: [string, string];
  Wxiw: [string, string];
  eval_a: string;
  eval_b: string;
  eval_c: string;
  eval_s1: string;
  eval_s2: string;
  eval_zw: string;
}

export interface VerificationKey {
  protocol: string;
  curve: string;
  nPublic: number;
  vk_alpha_1: [string, string];
  vk_beta_2: [[string, string], [string, string]];
  vk_gamma_2: [[string, string], [string, string]];
  vk_delta_2: [[string, string], [string, string]];
  vk_alphabeta_12: [[[string, string], [string, string]], [[string, string], [string, string]]];
  IC: [string, string][];
}
`;
        
        const typesFile = path.join(__dirname, "../../frontend/src/types/zk.ts");
        const typesDir = path.dirname(typesFile);
        if (!fs.existsSync(typesDir)) {
            fs.mkdirSync(typesDir, { recursive: true });
        }
        fs.writeFileSync(typesFile, typesContent);
        console.log(`✅ TypeScript types generated: ${typesFile}`);
        
        console.log("\n🎉 Verifier generation completed!");
        console.log("\n📋 Next steps:");
        console.log("1. Compile and deploy contracts: npm run contracts:compile && npm run contracts:deploy:testnet");
        console.log("2. Test the verifier with a proof");
        console.log("3. Integrate with frontend");
        
    } catch (error) {
        console.error("❌ Verifier generation failed:", error);
        process.exit(1);
    }
}

if (require.main === module) {
    main()
        .then(() => process.exit(0))
        .catch((error) => {
            console.error(error);
            process.exit(1);
        });
}